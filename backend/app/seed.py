def _ensure_admin(db: Session) -> Profile:
    admin = db.scalar(select(Profile).where(Profile.email == ADMIN_EMAIL))
    if admin is None:
        admin = Profile(**ADMIN)
        db.add(admin)
        db.flush()
    elif admin.role != "admin":
        admin.role = "admin"
    return admin


def _build_course(spec: dict, author_id: int) -> Course:
    course = Course(
        title=spec["title"],
        description=spec["description"],
        category=spec["category"],
        level=spec["level"],
        duration_hours=spec["duration_hours"],
        author_id=author_id,
    )
    for module_spec in spec["modules"]:
        module = Module(title=module_spec["title"], position=module_spec["position"])
        for lesson_spec in module_spec["lessons"]:
            lesson = Lesson(
                title=lesson_spec["title"],
                content=lesson_spec["content"],
                position=lesson_spec["position"],
            )
            quiz_spec = lesson_spec.get("quiz")
            if quiz_spec is not None:
                quiz = Quiz(title=quiz_spec["title"])
                for position, q in enumerate(quiz_spec["questions"], start=1):
                    quiz.questions.append(
                        Question(
                            text=q["text"],
                            options=list(q["options"]),
                            correct_index=q["correct_index"],
                            explanation=q["explanation"],
                            position=position,
                        )
                    )
                lesson.quiz = quiz
            module.lessons.append(lesson)
        course.modules.append(module)
    return course


def seed(db: Session) -> dict[str, int]:
    """Insert demo data. Idempotent: existing courses (matched by title) are left untouched.

    Returns the number of rows created by this call.
    """
    created = {"profiles": 0, "courses": 0}
    existing_admin = db.scalar(select(Profile.id).where(Profile.email == ADMIN_EMAIL))
    admin = _ensure_admin(db)
    if existing_admin is None:
        created["profiles"] += 1

    for spec in COURSES:
        already = db.scalar(select(Course.id).where(Course.title == spec["title"]))
        if already is not None:
            continue
        db.add(_build_course(spec, author_id=admin.id))
        created["courses"] += 1

    db.commit()
    return created


def main() -> None:
    with SessionLocal() as db:
        result = seed(db)
    print(f"Seed complete: {result}")


if __name__ == "__main__":
    main()
